"""Copy local SQLite expenses and budgets to the PostgreSQL database in DATABASE_URL."""
import os
import sqlite3
import sys
from pathlib import Path

import psycopg
from psycopg.rows import dict_row

SQLITE_PATH = Path(__file__).resolve().parent / "instance" / "expenses.db"


def main():
    url = os.environ.get("DATABASE_URL", "").strip()
    if not url:
        sys.exit("DATABASE_URL is not set in this PowerShell session.")
    if not SQLITE_PATH.exists():
        sys.exit(f"SQLite database not found: {SQLITE_PATH}")

    with sqlite3.connect(SQLITE_PATH) as src:
        src.row_factory = sqlite3.Row
        expenses = [dict(r) for r in src.execute(
            "SELECT id, date, category, amount, description FROM expenses ORDER BY id"
        ).fetchall()]
        budgets = [dict(r) for r in src.execute(
            "SELECT id, month, category, monthly_limit FROM budgets ORDER BY id"
        ).fetchall()]

    with psycopg.connect(url, row_factory=dict_row) as dst:
        dst.execute("""
            CREATE TABLE IF NOT EXISTS expenses (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                date TEXT NOT NULL, category TEXT NOT NULL,
                amount DOUBLE PRECISION NOT NULL CHECK(amount > 0),
                description TEXT DEFAULT ''
            )
        """)
        dst.execute("""
            CREATE TABLE IF NOT EXISTS budgets (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                month TEXT NOT NULL, category TEXT NOT NULL,
                monthly_limit DOUBLE PRECISION NOT NULL CHECK(monthly_limit > 0),
                UNIQUE(month, category)
            )
        """)
        for r in expenses:
            dst.execute("""INSERT INTO expenses (id,date,category,amount,description)
                VALUES (%s,%s,%s,%s,%s) ON CONFLICT (id) DO NOTHING""",
                (r["id"], r["date"], r["category"], r["amount"], r["description"]))
        for r in budgets:
            dst.execute("""INSERT INTO budgets (id,month,category,monthly_limit)
                VALUES (%s,%s,%s,%s) ON CONFLICT (id) DO NOTHING""",
                (r["id"], r["month"], r["category"], r["monthly_limit"]))
        for table in ("expenses", "budgets"):
            dst.execute(
                f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), "
                f"GREATEST(COALESCE((SELECT MAX(id) FROM {table}), 1), 1), "
                f"EXISTS(SELECT 1 FROM {table}))"
            )
        dst.commit()
        expense_count = dst.execute("SELECT COUNT(*) AS n FROM expenses").fetchone()["n"]
        budget_count = dst.execute("SELECT COUNT(*) AS n FROM budgets").fetchone()["n"]

    print(f"Migration finished: {expense_count} expenses, {budget_count} budgets in Neon.")


if __name__ == "__main__":
    main()
